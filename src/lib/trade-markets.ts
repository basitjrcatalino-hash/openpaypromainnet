/**
 * Master Token / Market Registry for OpenPay Pro Spot + Perpetual.
 *
 * Sources: CoinGecko + CoinMarketCap top market-cap lists + prior curated
 * majors. Each row enables Spot (`*USDT`) and Perpetual (`*USDT.P`) by default.
 *
 * Not listed as base pairs: quote stables / dollar funds (USDT, USDC, TUSD,
 * DAI, USDS, USD1, USDe, USDG, PYUSD, USDD, RLUSD, FDUSD, EURC, …) and
 * non-tradeable RWA/fund tickers from homepage rankings.
 *
 * Adding a listed market = one `market({...})` row. TradingView / CoinGecko /
 * CMC URLs are generated from symbol + slugs.
 */

import type { MajorTokenId } from "@/lib/major-tokens";
import { isMajorTokenId } from "@/lib/major-tokens";

export type TradeMarketStatus = "listed" | "delisted";

export type TradeMarketDef = {
  symbol: string;
  name: string;
  pair: string;
  network: string;
  contract_address: string | null;
  coingecko_slug: string;
  coinmarketcap_slug: string;
  logo: string;
  majorId?: MajorTokenId;
  status: TradeMarketStatus;
  spot_enabled: boolean;
  perpetual_enabled: boolean;
  margin_enabled: boolean;
  max_leverage: number;
  tick_size: number;
  step_size: number;
  min_qty: number;
  max_qty: number;
  maker_fee: number;
  taker_fee: number;
  spot_tv: string;
  perp_tv: string;
  binance_futures?: string;
  okx_swap?: string;
  gate_futures?: string;
  bybit_linear?: string;
  cmc_rank?: number;
  cmc_ucid?: number;
};

export function tradingViewSpotUrl(symbol: string): string {
  return `https://www.tradingview.com/symbols/${symbol.toUpperCase()}USDT/`;
}

export function tradingViewPerpUrl(symbol: string): string {
  return `https://www.tradingview.com/symbols/${symbol.toUpperCase()}USDT.P/`;
}

export function coingeckoUrl(slug: string): string {
  return `https://www.coingecko.com/en/coins/${slug}`;
}

export function coinmarketcapUrl(slug: string): string {
  return `https://coinmarketcap.com/currencies/${slug}/`;
}

type MarketSeed = {
  symbol: string;
  name: string;
  network: string;
  coingecko_slug: string;
  coinmarketcap_slug?: string;
  logo: string;
  majorId?: MajorTokenId;
  contract_address?: string | null;
  spot_enabled?: boolean;
  perpetual_enabled?: boolean;
  margin_enabled?: boolean;
  max_leverage?: number;
  tick_size?: number;
  step_size?: number;
  min_qty?: number;
  max_qty?: number;
  maker_fee?: number;
  taker_fee?: number;
  spot_tv?: string;
  perp_tv?: string;
  binance_futures?: string | false;
  okx_swap?: string | false;
  gate_futures?: string | false;
  bybit_linear?: string | false;
  cmc_rank?: number;
  cmc_ucid?: number;
};

function market(seed: MarketSeed): TradeMarketDef {
  const symbol = seed.symbol.toUpperCase();
  const pair = `${symbol}USDT`;
  const inferred =
    seed.majorId ??
    (isMajorTokenId(symbol.toLowerCase())
      ? (symbol.toLowerCase() as MajorTokenId)
      : undefined);
  return {
    symbol,
    name: seed.name,
    pair,
    network: seed.network,
    contract_address: seed.contract_address ?? null,
    coingecko_slug: seed.coingecko_slug,
    coinmarketcap_slug: seed.coinmarketcap_slug ?? seed.coingecko_slug,
    logo: seed.logo,
    majorId: inferred,
    status: "listed",
    spot_enabled: seed.spot_enabled ?? true,
    perpetual_enabled: seed.perpetual_enabled ?? true,
    margin_enabled: seed.margin_enabled ?? true,
    max_leverage: seed.max_leverage ?? 20,
    tick_size: seed.tick_size ?? 0.01,
    step_size: seed.step_size ?? 0.0001,
    min_qty: seed.min_qty ?? 0.0001,
    max_qty: seed.max_qty ?? 1_000_000,
    maker_fee: seed.maker_fee ?? 0.0002,
    taker_fee: seed.taker_fee ?? 0.0005,
    spot_tv: seed.spot_tv ?? `BINANCE:${pair}`,
    perp_tv: seed.perp_tv ?? `OKX:${pair}.P`,
    binance_futures:
      seed.binance_futures === false ? undefined : (seed.binance_futures ?? pair),
    okx_swap:
      seed.okx_swap === false ? undefined : (seed.okx_swap ?? `${symbol}-USDT-SWAP`),
    gate_futures:
      seed.gate_futures === false ? undefined : (seed.gate_futures ?? `${symbol}_USDT`),
    bybit_linear:
      seed.bybit_linear === false ? undefined : (seed.bybit_linear ?? pair),
    cmc_rank: seed.cmc_rank,
    cmc_ucid: seed.cmc_ucid,
  };
}

