const BY_SYMBOL = new Map(TRADE_MARKETS.map((m) => [m.symbol, m]));

const _listedSymbols = TRADE_MARKETS.filter(
  (m) => m.status === "listed" && (m.spot_enabled || m.perpetual_enabled),
).map((m) => m.symbol);

if (_listedSymbols.length < 1) {
  throw new Error("Master Token Registry has no listed markets");
}

export const PERP_MARKETS = _listedSymbols as [string, ...string[]];
export type PerpMarket = (typeof PERP_MARKETS)[number];

export function getTradeMarket(symbol: string): TradeMarketDef | undefined {
  return BY_SYMBOL.get(symbol.toUpperCase());
}

export function requireTradeMarket(symbol: string): TradeMarketDef {
  const m = getTradeMarket(symbol);
  if (!m) throw new Error(`Unknown trade market: ${symbol}`);
  return m;
}

export function isTradeMarket(v: string): v is PerpMarket {
  return BY_SYMBOL.has(v.toUpperCase()) && getTradeMarket(v)?.status === "listed";
}

export function listedTradeMarkets(): TradeMarketDef[] {
  return TRADE_MARKETS.filter((m) => m.status === "listed");
}

export function marketsForMode(mode: "spot" | "futures"): TradeMarketDef[] {
  return listedTradeMarkets().filter((m) =>
    mode === "spot" ? m.spot_enabled : m.perpetual_enabled,
  );
}
